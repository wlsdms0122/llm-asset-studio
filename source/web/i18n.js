// A viewer's choice is kept in this browser; without one, the browser's own language decides.
const language = (() => {
  try {
    const saved = localStorage.getItem("language");
    if (LANGUAGES.some(([code]) => code === saved)) return saved;
  } catch {}
  return (navigator.language || "").toLowerCase().startsWith("ko") ? "ko" : "en";
})();

function t(text, values = {}) {
  const chosen = language === "ko" ? KO[text] ?? text : text;
  return chosen.replace(/\{(\w+)\}/g, (slot, key) => key in values ? values[key] : slot);
}

function tn(singular, plural, count, values = {}) {
  return t(count === 1 ? singular : plural, { count, ...values });
}

function setLanguage(code) {
  try { localStorage.setItem("language", code); } catch {}
  location.reload();
}

// The shell's fixed words: data-t translates the text, data-t-title the title and aria-label.
document.documentElement.lang = language;
document.querySelectorAll("[data-t]").forEach(node => { node.textContent = t(node.textContent); });
document.querySelectorAll("[data-t-title]").forEach(node => {
  node.title = t(node.title);
  if (node.hasAttribute("aria-label")) node.setAttribute("aria-label", t(node.getAttribute("aria-label")));
});
